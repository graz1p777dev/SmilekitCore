// Товароучёт как подписчик, а не как кусок канала.
//
// Правило простое: коробка отгружается только на подтверждённый чек. Раньше
// это списание стояло прямо в обработчике чека WhatsApp — то есть остаток
// умел уменьшаться ровно в одном канале, и любой новый канал пришлось бы
// учить тому же заново. Теперь это подписка на факт «заказ создан».
//
// Реакция в переписке для триггера не годится: вебхуки Green API событий
// реакций не отдают — поэтому подтверждением служит проверка чека.

import { defineModule, on } from '@/core'
import { decrementStock } from '../greenapi/config'

export const inventory = defineModule({
  id: 'inventory',
  title: 'Товароучёт (остаток на складе)',
  setup() {
    on('order.created', async ({ verified }) => {
      if (!verified) return
      await decrementStock(1)
    })
  },
})
