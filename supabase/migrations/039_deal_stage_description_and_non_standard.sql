-- ============================================================
-- Migration 039: описание этапов воронки + этап «Нестандартный запрос»
--
-- 1. deal_stages.description — короткая заметка о том, что за этап и когда
--    сделка сюда попадает. Раньше такого поля не было — при добавлении
--    этапов через настройки (Sprint-панель по образцу DepartmentsPanel/
--    RolesPanel) владелец должен уметь оставить пояснение, не только имя.
--
-- 2. Новый этап «Нестандартный запрос» — бот Smilekit (bot/smilekit_bot/
--    __main__.py, действие non_standard_request) переносит сюда сделки при
--    жалобе, запросе возврата или вопросе о сотрудничестве/опте: это не
--    обычный шаг воронки «к покупке», а сигнал, что дальше клиента должен
--    вести человек. sort_order — в конце списка, чтобы не сбивать порядок
--    существующих этапов (владелец мог их уже переставить).
-- ============================================================

ALTER TABLE public.deal_stages ADD COLUMN IF NOT EXISTS description TEXT;

INSERT INTO public.deal_stages (name, sort_order, kind, color, is_default, description)
SELECT 'Нестандартный запрос', 12, 'normal', '#b91c1c', FALSE,
       'Жалоба, запрос возврата или вопрос о сотрудничестве/опте — сюда бот '
       || 'переносит сделку вместо обычного шага воронки, разбирает человек.'
WHERE NOT EXISTS (
  SELECT 1 FROM public.deal_stages WHERE name = 'Нестандартный запрос'
);
