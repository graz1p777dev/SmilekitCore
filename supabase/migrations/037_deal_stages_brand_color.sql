-- Migration 037: цвет этапа воронки под бренд Smilekit
--
-- Названия и порядок этапов из 036 не трогаем: они описывают путь клиента
-- в общем виде (первое обращение → выявление потребности → предложение →
-- возражения → готовность заказать → передача менеджеру → покупка) и
-- совпадают с тем, как бот Smilekit доводит клиента до заказа. Менять их
-- вслепую нельзя — владелец мог их уже переименовать.
--
-- Правится ровно одно: этап «Готов к покупке» был засеян цветом #e11d1d —
-- это фирменный красный прежнего магазина. После ребренда красный отдан
-- сигналу об ошибке, поэтому на доске он читается как «что-то сломалось».
-- Ставим янтарный #f5a623 — акцент второго уровня в текущей системе.
--
-- Идемпотентно и безопасно: если владелец уже переименовал этап или сам
-- сменил цвет, UPDATE не заденет ни одной строки.
-- ============================================================

UPDATE public.deal_stages
   SET color = '#f5a623'
 WHERE name = 'Готов к покупке'
   AND color = '#e11d1d';
